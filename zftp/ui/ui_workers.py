class Events(QObject):
    done = Signal(object)
    failed = Signal(object)
    progress = Signal(object, object)
class Job(QRunnable):
    def __init__(self, fn):
        super().__init__()
        self.fn = fn
        self.events = Events()

    def run(self):
        try:
            self.events.done.emit(self.fn(self.events.progress.emit))
        except BaseException as exc:
            self.events.failed.emit(exc)
